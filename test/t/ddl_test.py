	def test_shared_root_info_not_using_undo(self):
		node = self.node
		node.start()
		node.safe_psql("""
			CREATE EXTENSION IF NOT EXISTS orioledb;

			CREATE TABLE test (
				id integer
			) USING orioledb;
		""")

		con1 = node.connect()

		con1.begin()

		con1.execute("""
			INSERT INTO test(id) VALUES (1);
		""")

		relfilenode = con1.execute("""
			SELECT relfilenode from pg_class WHERE oid = 'test'::regclass::oid;
		""")[0][0]

		self.assertEqual(
		    con1.execute(f"""
			SELECT r->'tupHdr'->'deleted'
				FROM orioledb_sys_tree_rows(1) r
					WHERE (r->'key'->'relnode')::int = {relfilenode};
		""")[0][0], False)

		con1.execute("""
			DROP TABLE test;
		""")

		self.assertEqual(
		    con1.execute(f"""
			SELECT r->'tupHdr'->'deleted'
				FROM orioledb_sys_tree_rows(1) r
					WHERE (r->'key'->'relnode')::int = {relfilenode};
		""")[0][0], False)

		con1.commit()

		self.assertEqual(
		    con1.execute(f"""
			SELECT COUNT(*) FROM orioledb_sys_tree_rows(1) r;
		""")[0][0], 0)

	def test_drop_index_concurrently_statement_timeout(self):
		"""
		DROP INDEX CONCURRENTLY keeps only ShareUpdateExclusiveLock, so
		during commit stage interrupts are switched off, so statement_timeout
		was never processed and the backend waited for the reader instead of
		failing.
		"""
		node = self.node
		node.start()
		node.safe_psql("""
			CREATE EXTENSION IF NOT EXISTS orioledb;

			CREATE TABLE o_test_drop_index (
				val_1 int PRIMARY KEY,
				val_2 int
			) USING orioledb;

			INSERT INTO o_test_drop_index
				SELECT v, v FROM generate_series(1, 100) v;

			CREATE INDEX o_test_drop_index_ix ON o_test_drop_index (val_2);
		""")

		reader = node.connect()
		dropper = node.connect(autocommit=True)
		try:
			reader.execute("SET idle_in_transaction_session_timeout = '30s';")
			reader.execute("SELECT * FROM o_test_drop_index LIMIT 1;")

			# Here we should catch an error by timeout, because the transaction
			# holds locks.
			dropper.execute("SET statement_timeout = '1s';")
			with self.assertRaises(Exception) as e:
				dropper.execute("""
					DROP INDEX CONCURRENTLY o_test_drop_index_ix;
				""")
			self.assertIn("canceling statement due to statement timeout",
			              str(e.exception))

			# The timed-out drop left the index in place but, as in upstream
			# PG, invalid: index_drop() commits indisvalid = false before
			# WaitForLockers() blocks, so the cancel does not roll it back.
			self.assertEqual([(False, )],
			                 dropper.execute("""
								 SELECT indisvalid FROM pg_index
									 WHERE indexrelid =
										   'o_test_drop_index_ix'::regclass;
							 """))

			# Nobody reads the table anymore, so the drop goes through.
			reader.rollback()
			dropper.execute("""
				DROP INDEX CONCURRENTLY o_test_drop_index_ix;
			""")
			self.assertEqual([(0, )],
			                 dropper.execute("""
								 SELECT count(*) FROM pg_class
									 WHERE relname = 'o_test_drop_index_ix';
							 """))
		finally:
			reader.close()
			dropper.close()

		node.stop()
